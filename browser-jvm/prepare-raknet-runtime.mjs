import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';

const execute = promisify(execFile);
const repository = path.resolve(import.meta.dirname, '..');
const sourceRoot = path.join(repository, '.tools/raknet-1a169895');
const sdk = path.join(repository, '.tools/emsdk-3.1.74-source/emsdk-3d6d8ee910466516a53e665b86458faa81dae9ba');
const compiler = path.join(sdk, 'upstream/emscripten/emcc.py');
const exports = ['rn_voice_init', 'rn_voice_set_complexity', 'rn_voice_state', 'rn_voice_deinit', 'rn_voice_destroy', 'pthread_self', 'rn_candidate_version', 'rn_peer_create', 'rn_peer_destroy', 'bs_create', 'bs_destroy', 'bs_live', 'bs_write', 'bs_read', 'bs_bits', 'bs_bytes', 'bs_read_offset', 'bs_data', 'bs_reset', 'bs_reset_read', 'bs_align_write', 'bs_align_read', 'malloc', 'free'];
const patches = new Map([
    ['FileList.cpp', { before: 'aac65637774aa8e9217f33f9eef2a53bf1a7230f6d940e6f37cab6b2d15502a5', after: '9d0c278675f7eb411a43b79cbd793725d8babbf75dfdcda1464749164295510a', from: '#include <sys/io.h>', to: '#if !defined(__EMSCRIPTEN__)\n#include <sys/io.h>\n#endif' }],
    ['ReplicaManager3.cpp', { before: 'f2337fdb245b0c1d8233c70dee59442d05239d04a088dd75c58449fb487a909a', after: '301759fe53c4b3c0b51900b8c924e1174034b0617cd8ce0bdb72e0cd554705a3', from: 'GetConnectionByGUID(participantListIn[index], worldId)==false', to: 'GetConnectionByGUID(participantListIn[index], worldId)==nullptr' }],
]);

/**
 * Fingerprints exact input or generated bytes.
 *
 * @param {Buffer|string} bytes - Actual file contents.
 * @returns {string} SHA-256 identity.
 */
function digest(bytes) {
    return createHash('sha256').update(bytes).digest('hex');
}

/**
 * Rejects output aliases before any compiler or source-copy write.
 *
 * @param {string} file - Exact owned output path.
 * @returns {Promise<void>} Completion after checking an existing file.
 */
async function checkOutputFile(file) {
    const status = await lstat(file).catch((error) => {
        if (error.code !== 'ENOENT') {
            throw error;
        }

        return undefined;
    });

    if (status && (!status.isFile() || status.isSymbolicLink() || status.nlink !== 1)) {
        throw new Error('RakNet output file aliases another owner');
    }
}

/**
 * Reads the exact official source set; no downloaded source executes here.
 *
 * @param {object} ledger - Pinned upstream identities.
 * @returns {Promise<Map<string, Buffer>>} Validated source bytes.
 */
async function readSources(ledger) {
    if (ledger.commit !== '1a169895a900c9fc4841c556e16514182b75faf8' || ledger.repository !== 'facebookarchive/RakNet'
        || ledger.files.length !== 264 || ledger.files.filter(({ name }) => name.endsWith('.cpp')).length !== 110
        || new Set(ledger.files.map(({ name }) => name)).size !== 264) {
        throw new Error('RakNet source ledger changed');
    }

    const canonical = await realpath(sourceRoot);

    if (canonical !== path.join(await realpath(repository), '.tools/raknet-1a169895')) {
        throw new Error('RakNet source directory escapes workspace');
    }

    const files = await Promise.all(ledger.files.map(async ({ name, sha256 }) => {
        if (!/^[\w.-]+\.(cpp|h)$/.test(name)) {
            throw new Error('Invalid RakNet source name');
        }

        const file = await realpath(path.join(canonical, name));
        const bytes = await readFile(file);

        if (!file.startsWith(`${canonical}${path.sep}`) || digest(bytes) !== sha256) {
            throw new Error(`Pinned RakNet source changed: ${name}`);
        }

        return [name, bytes];
    }));

    return new Map(files);
}

/**
 * Creates one contained directory at a time, rejecting junction escapes before descending.
 *
 * @param {string[]} parts - Remaining output path components.
 * @param {string} parent - Existing canonical parent.
 * @param {string} target - Canonical workspace target root.
 * @returns {Promise<void>} Completion of validated directory creation.
 */
async function createOutput(parts, parent, target) {
    if (parts.length === 0) {
        return;
    }

    const directory = path.join(parent, parts[0]);

    await mkdir(directory).catch((error) => {
        if (error.code !== 'EEXIST') {
            throw error;
        }
    });
    const canonical = await realpath(directory);

    if (canonical !== directory || !canonical.startsWith(`${target}${path.sep}`)) {
        throw new Error('RakNet output aliases or escapes through a junction');
    }

    await createOutput(parts.slice(1), canonical, target);
}

/**
 * Builds all pinned upstream engine units with the existing SDK; downloads or installs nothing.
 *
 * @param {string} outputDirectory - Owned workspace target subdirectory.
 * @returns {Promise<object>} Exact source, compiler, patch and generated output identities.
 */
export async function prepareRakNetRuntime(outputDirectory) {
    const output = path.resolve(outputDirectory);
    const targetPath = path.join(repository, 'target');

    if (!output.startsWith(`${targetPath}${path.sep}`)) {
        throw new Error('RakNet output must be a workspace target subdirectory');
    }

    const ledgerFile = path.join(import.meta.dirname, 'raknet-sources.json');
    const ledgerBytes = await readFile(ledgerFile);

    if (digest(ledgerBytes) !== 'a587fb660c3d2d2a7ba5ab690cff8fd2954afd357f09190d293b699500a9f341'
        || digest(await readFile(compiler)) !== 'fa058b37c97812c47c71abf337e315e37001abe239655514459af391d988cbcd') {
        throw new Error('Pinned RakNet ledger or Emscripten 3.1.74 compiler changed');
    }

    const ledger = JSON.parse(ledgerBytes);
    const sources = await readSources(ledger);
    const bridge = path.join(import.meta.dirname, 'raknet-engine.cpp');
    const bridgeSha = digest(await readFile(bridge));
    const voiceHeader = path.join(import.meta.dirname, 'rakvoice-engine.h');
    const voiceHeaderSha = digest(await readFile(voiceHeader));
    const notices = new Map();

    await Promise.all([['RAKNET-LICENSE.txt', 'da7efae279531d6969da900e53da7b57be40ac983de32d24eeecec0f33cc25f3'], ['RAKNET-PATENTS.txt', 'bd76e337528d2e7bd9f5adb8e2be798c7b8ee7313316fcd9533e5d51cfdfa2f1']].map(async ([name, sha]) => {
        const bytes = await readFile(path.join(import.meta.dirname, name));

        if (digest(bytes) !== sha) {
            throw new Error(`Pinned RakNet notice changed: ${name}`);
        }

        notices.set(name, bytes);
    }));

    await mkdir(targetPath, { recursive: true });
    const target = await realpath(targetPath);

    if (target !== path.join(await realpath(repository), 'target')) {
        throw new Error('RakNet target escapes through a junction');
    }

    await createOutput([...path.relative(targetPath, output).split(path.sep), 'source'], target, target);
    const generated = ['raknet-engine.mjs', 'raknet-engine.wasm', 'raknet-engine.worker.js', 'raknet-manifest.json', 'raknet-build.log', ...notices.keys()];

    await Promise.all([...generated.map((name) => path.join(output, name)), ...[...sources.keys()].map((name) => path.join(output, 'source', name))].map(checkOutputFile));
    const adapted = new Map();

    for (const [name, bytes] of sources) {
        const patch = patches.get(name);
        let result = bytes;

        if (patch) {
            const text = bytes.toString();

            if (digest(bytes) !== patch.before || text.split(patch.from).length !== 2) {
                throw new Error(`RakNet patch precondition failed: ${name}`);
            }

            result = Buffer.from(text.replace(patch.from, patch.to));

            if (digest(result) !== patch.after) {
                throw new Error(`RakNet patch identity failed: ${name}`);
            }
        }

        adapted.set(name, result);
    }

    await Promise.all([...adapted].map(([name, bytes]) => writeFile(path.join(output, 'source', name), bytes)));
    const arguments_ = ['-3', compiler, '-std=c++11', '-O1', '-g2', '-pthread', `-I${path.join(output, 'source')}`, bridge,
        ...ledger.files.filter(({ name }) => name.endsWith('.cpp')).map(({ name }) => path.join(output, 'source', name)),
        '-sMODULARIZE=1', '-sEXPORT_ES6=1', '-sENVIRONMENT=web,node', '-sALLOW_MEMORY_GROWTH=1', '-sPTHREAD_POOL_SIZE=0',
        '-sEXPORTED_RUNTIME_METHODS=["PThread"]', `-sEXPORTED_FUNCTIONS=${JSON.stringify(exports.map((name) => `_${name}`))}`,
        '-o', path.join(output, 'raknet-engine.mjs')];
    const result = await execute('py', arguments_, { env: { ...process.env, EM_CONFIG: path.join(sdk, '.emscripten') }, timeout: 180_000, maxBuffer: 16_777_216, windowsHide: true }).catch(async (error) => {
        await writeFile(path.join(output, 'raknet-build.log'), `${error.stdout ?? ''}\n${error.stderr ?? ''}\n${error}`);

        throw error;
    });

    await writeFile(path.join(output, 'raknet-build.log'), `${result.stdout}\n${result.stderr}`);
    await readSources(ledger);

    if (digest(await readFile(ledgerFile)) !== digest(ledgerBytes) || digest(await readFile(bridge)) !== bridgeSha || digest(await readFile(voiceHeader)) !== voiceHeaderSha) {
        throw new Error('RakNet build input changed during compilation');
    }

    await Promise.all([...adapted].map(async ([name, bytes]) => {
        if (digest(await readFile(path.join(output, 'source', name))) !== digest(bytes)) {
            throw new Error(`Adapted RakNet source changed during compilation: ${name}`);
        }
    }));
    const manifest = {
        candidateVersion: ledger.candidateVersion, candidateCommit: ledger.commit, installedVersion: 'unknown', versionMatchVerified: false,
        sourceFiles: ledger.files.length, translationUnits: 110, compilerVersion: '3.1.74', bridgeSha, voiceHeaderSha,
        sourceLedgerSha: digest(ledgerBytes), patches: [...patches].map(([file, { before, after }]) => ({ file, before, after })),
        arguments: arguments_, moduleSha: digest(await readFile(path.join(output, 'raknet-engine.mjs'))),
        wasmSha: digest(await readFile(path.join(output, 'raknet-engine.wasm'))),
    };

    await Promise.all([...notices].map(([name, bytes]) => writeFile(path.join(output, name), bytes)));
    await writeFile(path.join(output, 'raknet-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

    return manifest;
}
